// ============================================================
// 最新年度出口数据（默认 2024）
// ============================================================
const DEFAULT_YEAR = 2024

export function getProvinceExports(year = DEFAULT_YEAR) {
  const y = provinceExportData.find(d => d.year === year)
  return y ? y.provinces : []
}

export function getCountryExports(year = DEFAULT_YEAR) {
  const y = countryExportData.find(d => d.year === year)
  return y ? y.countries : []
}

// ============================================================
// 按全国国别结构比例，估算「某省 → 各国」的贸易流
// 规则：flow(p, c) = 省出口总额 × (全国对该国出口额 / 全国总出口额)
// ============================================================
export function estimateProvinceFlows(provinceName, year = DEFAULT_YEAR, topK = 20) {
  const provList = getProvinceExports(year)
  const ctryList = getCountryExports(year)

  const prov = provList.find(p => p.name === provinceName
    || p.name.replace(/省|市|自治区|壮族|回族|维吾尔|特别行政/g, '').includes(
      provinceName.replace(/省|市|自治区|壮族|回族|维吾尔|特别行政/g, '')))
  if (!prov) return null

  const totalNational = ctryList.reduce((s, c) => s + c.value, 0)
  if (!totalNational) return null

  const flows = ctryList
    .filter(c => COUNTRY_CENTER[c.name])
    .map(c => ({
      country: c.name,
      value: prov.value * c.value / totalNational,
      from: PROVINCE_CENTER[provinceName] || PROVINCE_CENTER['浙江省'],
      to: COUNTRY_CENTER[c.name],
      share: prov.value ? (prov.value * c.value / totalNational / prov.value) : 0,
    }))
    .filter(f => f.value >= 500000)
    .sort((a, b) => b.value - a.value)
    .slice(0, topK)

  return {
    province: provinceName,
    provinceValue: prov.value,
    totalValue: flows.reduce((s, f) => s + f.value, 0),
    flows,
    year,
  }
}

